#!/usr/bin/env python3
"""Regenerate the docs and schemas that are built from code.

    python scripts/gen_docs.py          # write everything
    python scripts/gen_docs.py --check  # exit 1 if anything is stale (used by tests/CI)

Generates:
  schemas/{8bt,8bms,plugin,ops}.schema.json, schemas/openapi.json
  the ops blocks in docs/cli-reference.md and AGENTS.md (between GENERATED markers)
  llms-full.txt (README + AGENTS + docs + skills in one file)
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("EIGHTBMS_NO_PLUGINS", "1")
import eightbit_studio as bms  # noqa: E402

BEGIN, END = "<!-- BEGIN GENERATED: ops -->", "<!-- END GENERATED: ops -->"

# The order docs appear in llms-full.txt (anything else in docs/ is appended alphabetically).
DOC_ORDER = ["README.md", "getting-started.md", "agent-framework.md", "cli-reference.md", "score-format.md",
             "note-language.md", "gui-guide.md", "terminal-studio.md", "exporting.md", "python-api.md",
             "http-api.md", "mcp.md", "acp.md", "midi-apc.md", "apc-hardware-testing.md", "ml.md", "architecture.md", "faq.md", "glossary.md"]


def _read(p: Path) -> str:
    """Read text with LF line endings (a Windows checkout may have CRLF)."""
    return p.read_text(encoding="utf-8").replace("\r\n", "\n")


def core_ops():
    return [t for t in bms.op_tools() if t.get("owner", "core") == "core"]


def _dump(obj) -> str:
    return json.dumps(obj, indent=2) + "\n"


def schema_files() -> dict:
    return {
        "schemas/8bt.schema.json": _dump(bms.score_json_schema()),
        "schemas/8bms.schema.json": _dump(bms.project_json_schema()),
        "schemas/plugin.schema.json": _dump(bms.MANIFEST_SCHEMA),
        "schemas/ops.schema.json": _dump({n: o.json_schema() for n, o in bms.OPS.items() if o.owner == "core"}),
        "schemas/openapi.json": _dump(bms.openapi_spec()),
    }


def _one_line(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip().replace("|", "\\|")


def ops_reference_md() -> str:
    lines = ["<a id=\"ops\"></a>", "", f"{len(core_ops())} ops, generated from the registry (`8bms tools --json` has full input schemas). Every op also takes `_fields` (CLI `--fields`) to trim its result.", ""]
    for t in core_ops():
        lines += [f"### `{t['name']}`", "", _one_line(t["description"]), "", "```sh", t["cli"], "```", ""]
        props = t["inputSchema"].get("properties", {})
        req = set(t["inputSchema"].get("required", []))
        if props:
            lines += ["| arg | type | default | help |", "|---|---|---|---|"]
            for k, v in props.items():
                if k.startswith("_"):
                    continue
                d = v.get("default")
                d = "required" if k in req else ("" if d is None else f"`{json.dumps(d)}`")
                typ = v.get("type", "any")
                typ = "/".join(typ) if isinstance(typ, list) else typ
                lines.append(f"| `{k}` | {typ} | {d} | {_one_line(v.get('description', ''))} |")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def ops_table_md() -> str:
    lines = ["| op | what it does | CLI |", "|---|---|---|"]
    for t in core_ops():
        cli = t["cli"].replace("|", "\\|")
        lines.append(f"| `{t['name']}` | {_one_line(t['description'])} | `{cli}` |")
    return "\n".join(lines) + "\n"


def fill_block(text: str, body: str, path: str) -> str:
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{path}: missing {BEGIN} / {END} markers")
    pre, rest = text.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    return f"{pre}{BEGIN}\n{body}{END}{post}"


def doc_paths() -> list:
    docs = ROOT / "docs"
    seen = [docs / n for n in DOC_ORDER if (docs / n).exists()]
    rest = sorted((p for p in docs.rglob("*.md") if p not in seen), key=lambda p: p.relative_to(ROOT).as_posix())  # same order on every OS
    return seen + rest


def llms_full(generated: dict) -> str:
    def read(rel):
        return generated.get(rel) or _read(ROOT / rel)
    names = ["README.md", "AGENTS.md"] + [p.relative_to(ROOT).as_posix() for p in doc_paths()]
    names += [p.relative_to(ROOT).as_posix() for p in sorted((ROOT / "skills").glob("*/SKILL.md"), key=lambda p: p.parent.name)]
    parts = [(n, read(n)) for n in names]
    head = ("# 8Bit Music Code Studio: full docs for LLMs\n\n"
            "> Generated by scripts/gen_docs.py: README, AGENTS.md, docs/ and skills/ in one file. "
            "The short index is llms.txt.\n")
    return head + "".join(f"\n\n---\n<!-- file: {name} -->\n\n{txt.strip()}\n" for name, txt in parts)


def generate() -> dict:
    out = schema_files()
    cli = _read(ROOT / "docs/cli-reference.md")
    out["docs/cli-reference.md"] = fill_block(cli, ops_reference_md(), "docs/cli-reference.md")
    out["AGENTS.md"] = fill_block(_read(ROOT / "AGENTS.md"), ops_table_md(), "AGENTS.md")
    out["llms-full.txt"] = llms_full(out)
    return out


def main(argv=None) -> int:
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    stale = []
    for rel, txt in generate().items():
        p = ROOT / rel
        cur = _read(p) if p.exists() else None
        if cur != txt:
            stale.append(rel)
            if not check:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(txt, encoding="utf-8", newline="\n")
    if check:
        if stale:
            print("stale (run python scripts/gen_docs.py):", ", ".join(stale))
            return 1
        print("docs up to date")
        return 0
    print("updated:", ", ".join(stale) if stale else "nothing (already up to date)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
